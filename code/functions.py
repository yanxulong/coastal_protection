def _required_inputs(project) -> dict[str, Path]:
    return {
        "NOAA shoreline study boundary": project.paths["study_area_boundary"],
        "TIGER county boundaries": project.paths["county_boundaries"],
        "HURDAT2 storm tracks": project.paths["hurdat2_tracks"],
        "NOAA SLOSH category inundation data": project.paths["slosh_root"],
        "coastal-only 3DEP tile manifest": project.paths["dem_tile_manifest"],
        "downloaded 3DEP DEM tiles": project.paths["dem_tiles"],
    }


def _present(path: Path) -> bool:
    return path.is_file() and path.stat().st_size > 0 or path.is_dir()


def validate_project_layout(project) -> dict[str, object]:
    """Create project work directories; never download or overwrite research data."""
    directory_keys = ("raw", "processed", "figures", "tables", "logs", "msi")
    created: list[str] = []
    for key in directory_keys:
        path = project.paths[key]
        path.mkdir(parents=True, exist_ok=True)
        created.append(str(path))

    inputs = _required_inputs(project)
    available = 0
    for label, path in inputs.items():
        exists = _present(path)
        available += int(exists)
        print(f"[input] {'READY' if exists else 'MISSING'} {label}: {path}")
    return {
        "created_directories": created,
        "available_inputs": available,
        "required_inputs": len(inputs),
        "all_inputs_available": available == len(inputs),
    }


def audit_stormarea_inputs(project) -> dict[str, object]:
    """Inventory the data required before constructing potential impact areas."""
    inputs = _required_inputs(project)
    missing: list[str] = []
    for label, path in inputs.items():
        present = _present(path)
        print(f"[input] {'READY' if present else 'MISSING'} {label}: {path}")
        if not present:
            missing.append(label)
    print(f"[audit] {len(inputs) - len(missing)}/{len(inputs)} inputs present")
    return {"inputs": inputs, "missing": missing, "ready": not missing}


def prepare_msi_dem_download(project) -> dict[str, str]:
    """Generate an MSI-side resumable downloader; this task does not submit it."""
    script_path = project.paths["msi_dem_download_script"]
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script = textwrap.dedent(
        r'''\
        #!/usr/bin/env bash
        # Generated by code/run.py --task prepare_msi_dem_download.
        # Submit only after checking current MSI Slurm and storage limits.
        set -Eeuo pipefail

        PROJECT_ROOT="${COASTAL_PROTECTION_PROJECT_ROOT:-/scratch.global/yxlong/projects/coastal_protection}"
        MANIFEST="${COASTAL_DEM_TILE_MANIFEST:-$PROJECT_ROOT/data/raw/usgs_3dep_13arcsec_dem/dem_tile_manifest_final_shoreline_counties_except_great_lakes.csv}"
        DEST="${COASTAL_DEM_TILE_DIR:-$PROJECT_ROOT/data/raw/usgs_3dep_13arcsec_dem/tiles}"
        mkdir -p "$DEST"
        [[ -s "$MANIFEST" ]] || { printf '[error] tile manifest missing: %s\n' "$MANIFEST" >&2; exit 2; }

        python3 - "$MANIFEST" "$DEST" <<'PY'
        import csv
        import hashlib
        import os
        import subprocess
        import sys
        from datetime import datetime, timezone
        from pathlib import Path
        from urllib.parse import unquote, urlparse

        manifest, destination = Path(sys.argv[1]), Path(sys.argv[2])
        destination.mkdir(parents=True, exist_ok=True)

        def field(row, names):
            for name in names:
                value = row.get(name)
                if value:
                    return value.strip()
            return ""

        def sha256(path):
            digest = hashlib.sha256()
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
                    digest.update(block)
            return digest.hexdigest()

        def matches(path, expected_bytes, expected_sha):
            if not path.is_file() or path.stat().st_size == 0:
                return False
            if expected_bytes and path.stat().st_size != expected_bytes:
                return False
            if expected_sha and sha256(path).lower() != expected_sha.lower():
                return False
            return True

        with manifest.open(newline="", encoding="utf-8-sig") as source:
            reader = csv.DictReader(source)
            if not reader.fieldnames:
                raise SystemExit("Manifest has no CSV header.")
            rows = list(reader)

        record_path = destination.parent / "downloaded_tiles_manifest.tsv"
        completed = 0
        for index, row in enumerate(rows, start=1):
            url = field(row, ("url", "download_url", "downloadURL", "DownloadURL"))
            if not url:
                raise SystemExit(f"Manifest row {index}: missing URL column/value.")
            filename = field(row, ("filename", "file_name", "tile_name", "name"))
            if not filename:
                filename = Path(unquote(urlparse(url).path)).name
            if not filename or Path(filename).name != filename:
                raise SystemExit(f"Manifest row {index}: unsafe or missing filename {filename!r}.")
            expected_raw = field(row, ("expected_bytes", "size_bytes", "bytes", "sizeInBytes"))
            expected_bytes = int(expected_raw) if expected_raw else 0
            expected_sha = field(row, ("sha256", "SHA256")).lower()
            target = destination / filename
            partial = target.with_name(target.name + ".part")

            if matches(target, expected_bytes, expected_sha):
                print(f"[skip] {index}/{len(rows)} {filename}: verified existing file")
            else:
                if target.exists():
                    raise SystemExit(
                        f"Existing file fails manifest checks; preserved without overwrite: {target}"
                    )
                print(f"[download] {index}/{len(rows)} {filename}")
                command = [
                    "curl", "--fail", "--location", "--retry", "5", "--retry-delay", "5",
                    "--continue-at", "-", "--progress-bar", "--output", str(partial), url,
                ]
                subprocess.run(command, check=True)
                if expected_bytes and partial.stat().st_size != expected_bytes:
                    raise SystemExit(
                        f"Size mismatch for {filename}: {partial.stat().st_size} != {expected_bytes}; "
                        "partial file retained for diagnosis/resume."
                    )
                actual_sha = sha256(partial)
                if expected_sha and actual_sha.lower() != expected_sha:
                    raise SystemExit(
                        f"SHA-256 mismatch for {filename}; partial file retained for diagnosis."
                    )
                os.replace(partial, target)

            actual_sha = sha256(target)
            with record_path.open("a", encoding="utf-8") as record:
                record.write(
                    f"{filename}\t{url}\t{target.stat().st_size}\t{actual_sha}\t"
                    f"{datetime.now(timezone.utc).isoformat()}\n"
                )
            completed += 1
        print(f"[complete] {completed} DEM tiles present and checksum-recorded.")
        print(f"[manifest] {record_path}")
        PY
        '''
    ).lstrip()
    script_path.write_text(script, encoding="utf-8")
    script_path.chmod(0o755)
    print(f"[prepared] MSI DEM downloader: {script_path}")
    print("[policy] No download submitted; inspect live MSI limits before sbatch.")
    return {"script": str(script_path), "manifest": str(project.paths["dem_tile_manifest"])}


class _HrefParser(HTMLParser):
    """Collect links from NOAA directory and archive pages."""

    def __init__(self) -> None:
        super().__init__()
        self.hrefs: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag.lower() == "a":
            href = dict(attrs).get("href")
            if href:
                self.hrefs.append(href)


def _fetch_url(url: str) -> bytes:
    request = Request(url, headers={"User-Agent": "coastal-protection-research/1.0"})
    with urlopen(request, timeout=120) as response:
        return response.read()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _save_source(url: str, destination: Path) -> dict[str, object]:
    """Download one source without overwriting an existing snapshot file."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    payload = _fetch_url(url)
    if destination.exists():
        existing_sha = _sha256(destination)
        incoming_sha = hashlib.sha256(payload).hexdigest()
        if existing_sha != incoming_sha:
            raise FileExistsError(
                f"Snapshot file differs from current source; preserved existing file: {destination}"
            )
    else:
        temporary = destination.with_name(destination.name + ".part")
        temporary.write_bytes(payload)
        temporary.replace(destination)
    return {
        "url": url,
        "path": str(destination),
        "bytes": destination.stat().st_size,
        "sha256": _sha256(destination),
    }


def _nhc_hurdat_sources() -> list[dict[str, str]]:
    """Discover latest Atlantic and Northeast Pacific HURDAT2 files from NHC."""
    pages = (
        "https://www.nhc.noaa.gov/data/",
        "https://www.nhc.noaa.gov/data/hurdat/",
    )
    hrefs: set[str] = set()
    errors: list[str] = []
    for page in pages:
        try:
            parser = _HrefParser()
            parser.feed(_fetch_url(page).decode("utf-8", errors="replace"))
            hrefs.update(urljoin(page, href) for href in parser.hrefs)
        except Exception as exc:
            errors.append(f"{page}: {exc}")

    candidates: dict[str, tuple[int, str, str]] = {}
    pattern = re.compile(r"hurdat2.*\.txt$", re.IGNORECASE)
    year_range = re.compile(r"((?:18|19|20)\d{2})[-_]((?:18|19|20)\d{2})")
    for url in hrefs:
        filename = Path(unquote(urlparse(url).path)).name
        if not pattern.fullmatch(filename):
            continue
        match = year_range.search(filename)
        if not match:
            continue
        first_year, last_year = map(int, match.groups())
        lower_name = filename.lower()
        if "nepac" in lower_name or first_year == 1949:
            basin = "northeast_pacific"
        elif first_year == 1851:
            basin = "atlantic"
        else:
            continue
        # NHC filename date suffix gives deterministic preference among releases.
        version_match = re.search(r"-(\d{6})\.txt$", filename)
        version = version_match.group(1) if version_match else "000000"
        candidate = (last_year, version, url)
        if basin not in candidates or candidate[:2] > candidates[basin][:2]:
            candidates[basin] = candidate

    if not candidates:
        raise RuntimeError(
            "Could not discover NHC HURDAT2 files. " + "; ".join(errors)
        )
    missing_basins = {"atlantic", "northeast_pacific"} - set(candidates)
    if missing_basins:
        raise RuntimeError(f"NHC HURDAT2 archive missing basin links: {sorted(missing_basins)}")
    return [
        {"basin": basin, "last_year": str(values[0]), "url": values[2]}
        for basin, values in sorted(candidates.items())
    ]


def _nhc_2026_gis_best_tracks(start_year: int, end_year: int) -> list[str]:
    """Discover official NHC GIS best-track archives for the requested seasons."""
    index_url = "https://ftp.nhc.noaa.gov/atcf/gis/btk/"
    parser = _HrefParser()
    parser.feed(_fetch_url(index_url).decode("utf-8", errors="replace"))
    pattern = re.compile(r"^(?P<basin>al|ep)(?P<number>\d{2})(?P<year>\d{4})_best_track\.zip$", re.I)
    urls: list[str] = []
    for href in parser.hrefs:
        filename = Path(unquote(urlparse(href).path)).name
        match = pattern.fullmatch(filename)
        if match and start_year <= int(match.group("year")) <= end_year:
            urls.append(urljoin(index_url, href))
    return sorted(set(urls))


def download_nhc_storm_tracks(project) -> dict[str, object]:
    """Stage official NHC tracks for 1996-2026 in a dated, checksummed snapshot.

    Final HURDAT2 archives provide historical Atlantic and Northeast Pacific
    records through their published end year. Current-year GIS best-track ZIPs
    supplement HURDAT2 because the season is not yet finalized.
    """
    start_year = int(project.config.get("storm_start_year", 1996))
    end_year = int(project.config.get("storm_end_year", 2026))
    if start_year < 1851 or end_year < start_year:
        raise ValueError(f"Invalid storm-year range: {start_year}-{end_year}")

    retrieval_time = datetime.now(timezone.utc)
    snapshot = (
        project.paths["nhc_storm_track_root"]
        / "snapshots"
        / retrieval_time.strftime("%Y%m%d")
    )
    snapshot.mkdir(parents=True, exist_ok=True)

    hurdat_sources = _nhc_hurdat_sources()
    hurdat_files: list[dict[str, object]] = []
    for source in hurdat_sources:
        basin_dir = snapshot / "hurdat2" / source["basin"]
        filename = Path(unquote(urlparse(source["url"]).path)).name
        item = _save_source(source["url"], basin_dir / filename)
        item.update({"basin": source["basin"], "published_through_year": int(source["last_year"])})
        hurdat_files.append(item)

    gis_urls = _nhc_2026_gis_best_tracks(start_year, end_year)
    gis_files: list[dict[str, object]] = []
    for url in gis_urls:
        filename = Path(unquote(urlparse(url).path)).name
        gis_files.append(_save_source(url, snapshot / "nhc_gis_best_track" / filename))

    current_year_files = [
        item for item in gis_files
        if end_year == int(re.search(r"(\d{4})_best_track\.zip$", str(item["path"])).group(1))
    ]
    final_years = {int(item["published_through_year"]) for item in hurdat_files}
    if not hurdat_files or max(final_years) < min(end_year - 1, 2025):
        raise RuntimeError(
            f"Latest finalized HURDAT2 source ends before expected 2025 coverage: {sorted(final_years)}"
        )
    if end_year >= datetime.now(timezone.utc).year and not current_year_files:
        raise RuntimeError(
            f"No NHC GIS best-track files found for current season {end_year}; snapshot not marked complete."
        )

    manifest = {
        "dataset": "NHC tropical cyclone best tracks",
        "requested_years": {"start": start_year, "end": end_year},
        "retrieved_utc": retrieval_time.isoformat(),
        "status": {
            "final_hurdat2_through_year": max(final_years),
            "current_season_gis_tracks": "preliminary; current through retrieval date",
            "current_season_storm_count": len(current_year_files),
        },
        "scope_note": (
            "HURDAT2 source files contain full basin histories; downstream processing must filter "
            f"records to {start_year}-{end_year}. Current-season best-track GIS files are preliminary "
            "and may be revised after season-end review."
        ),
        "sources": {
            "nhc_hurdat2": "https://www.nhc.noaa.gov/data/",
            "nhc_gis_best_tracks": "https://ftp.nhc.noaa.gov/atcf/gis/btk/",
        },
        "hurdat2_files": hurdat_files,
        "gis_best_track_files": gis_files,
    }
    manifest_path = snapshot / "source_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"[download] Final HURDAT2 files: {len(hurdat_files)}")
    print(f"[download] NHC GIS best-track ZIPs: {len(gis_files)}")
    print(f"[coverage] finalized tracks through {max(final_years)}; current season preliminary")
    print(f"[manifest] {manifest_path}")
    return {
        "snapshot": str(snapshot),
        "manifest": str(manifest_path),
        "hurdat2_files": len(hurdat_files),
        "gis_best_track_files": len(gis_files),
        "current_season_storm_count": len(current_year_files),
    }
