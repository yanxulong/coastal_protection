def _required_inputs(project) -> dict[str, Path]:
    return {
        "NOAA shoreline study boundary": project.paths["study_area_boundary"],
        "TIGER county boundaries": project.paths["county_boundaries"],
        "HURDAT2 storm tracks": project.paths["hurdat2_tracks"],
        "NOAA SLOSH category inundation data": project.paths["slosh_root"],
        "coastal-only 3DEP tile manifest": project.paths["dem_tile_manifest"],
        "downloaded 3DEP DEM tiles": project.paths["dem_tiles"],
    }


def _present(path: Path) -> bool:
    return path.is_file() and path.stat().st_size > 0 or path.is_dir()


def validate_project_layout(project) -> dict[str, object]:
    """Create project work directories; never download or overwrite research data."""
    directory_keys = ("raw", "processed", "figures", "tables", "logs", "msi")
    created: list[str] = []
    for key in directory_keys:
        path = project.paths[key]
        path.mkdir(parents=True, exist_ok=True)
        created.append(str(path))

    inputs = _required_inputs(project)
    available = 0
    for label, path in inputs.items():
        exists = _present(path)
        available += int(exists)
        print(f"[input] {'READY' if exists else 'MISSING'} {label}: {path}")
    return {
        "created_directories": created,
        "available_inputs": available,
        "required_inputs": len(inputs),
        "all_inputs_available": available == len(inputs),
    }


def audit_stormarea_inputs(project) -> dict[str, object]:
    """Inventory the data required before constructing potential impact areas."""
    inputs = _required_inputs(project)
    missing: list[str] = []
    for label, path in inputs.items():
        present = _present(path)
        print(f"[input] {'READY' if present else 'MISSING'} {label}: {path}")
        if not present:
            missing.append(label)
    print(f"[audit] {len(inputs) - len(missing)}/{len(inputs)} inputs present")
    return {"inputs": inputs, "missing": missing, "ready": not missing}


def prepare_msi_dem_download(project) -> dict[str, str]:
    """Generate an MSI-side resumable downloader; this task does not submit it."""
    script_path = project.paths["msi_dem_download_script"]
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script = textwrap.dedent(
        r'''\
        #!/usr/bin/env bash
        # Generated by code/run.py --task prepare_msi_dem_download.
        # Submit only after checking current MSI Slurm and storage limits.
        set -Eeuo pipefail

        PROJECT_ROOT="${COASTAL_PROTECTION_PROJECT_ROOT:-/scratch.global/yxlong/projects/coastal_protection}"
        MANIFEST="${COASTAL_DEM_TILE_MANIFEST:-$PROJECT_ROOT/data/raw/usgs_3dep_13arcsec_dem/dem_tile_manifest_final_shoreline_counties_except_great_lakes.csv}"
        DEST="${COASTAL_DEM_TILE_DIR:-$PROJECT_ROOT/data/raw/usgs_3dep_13arcsec_dem/tiles}"
        mkdir -p "$DEST"
        [[ -s "$MANIFEST" ]] || { printf '[error] tile manifest missing: %s\n' "$MANIFEST" >&2; exit 2; }

        python3 - "$MANIFEST" "$DEST" <<'PY'
        import csv
        import hashlib
        import os
        import subprocess
        import sys
        from datetime import datetime, timezone
        from pathlib import Path
        from urllib.parse import unquote, urlparse

        manifest, destination = Path(sys.argv[1]), Path(sys.argv[2])
        destination.mkdir(parents=True, exist_ok=True)

        def field(row, names):
            for name in names:
                value = row.get(name)
                if value:
                    return value.strip()
            return ""

        def sha256(path):
            digest = hashlib.sha256()
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
                    digest.update(block)
            return digest.hexdigest()

        def matches(path, expected_bytes, expected_sha):
            if not path.is_file() or path.stat().st_size == 0:
                return False
            if expected_bytes and path.stat().st_size != expected_bytes:
                return False
            if expected_sha and sha256(path).lower() != expected_sha.lower():
                return False
            return True

        with manifest.open(newline="", encoding="utf-8-sig") as source:
            reader = csv.DictReader(source)
            if not reader.fieldnames:
                raise SystemExit("Manifest has no CSV header.")
            rows = list(reader)

        record_path = destination.parent / "downloaded_tiles_manifest.tsv"
        completed = 0
        for index, row in enumerate(rows, start=1):
            url = field(row, ("url", "download_url", "downloadURL", "DownloadURL"))
            if not url:
                raise SystemExit(f"Manifest row {index}: missing URL column/value.")
            filename = field(row, ("filename", "file_name", "tile_name", "name"))
            if not filename:
                filename = Path(unquote(urlparse(url).path)).name
            if not filename or Path(filename).name != filename:
                raise SystemExit(f"Manifest row {index}: unsafe or missing filename {filename!r}.")
            expected_raw = field(row, ("expected_bytes", "size_bytes", "bytes", "sizeInBytes"))
            expected_bytes = int(expected_raw) if expected_raw else 0
            expected_sha = field(row, ("sha256", "SHA256")).lower()
            target = destination / filename
            partial = target.with_name(target.name + ".part")

            if matches(target, expected_bytes, expected_sha):
                print(f"[skip] {index}/{len(rows)} {filename}: verified existing file")
            else:
                if target.exists():
                    raise SystemExit(
                        f"Existing file fails manifest checks; preserved without overwrite: {target}"
                    )
                print(f"[download] {index}/{len(rows)} {filename}")
                command = [
                    "curl", "--fail", "--location", "--retry", "5", "--retry-delay", "5",
                    "--continue-at", "-", "--progress-bar", "--output", str(partial), url,
                ]
                subprocess.run(command, check=True)
                if expected_bytes and partial.stat().st_size != expected_bytes:
                    raise SystemExit(
                        f"Size mismatch for {filename}: {partial.stat().st_size} != {expected_bytes}; "
                        "partial file retained for diagnosis/resume."
                    )
                actual_sha = sha256(partial)
                if expected_sha and actual_sha.lower() != expected_sha:
                    raise SystemExit(
                        f"SHA-256 mismatch for {filename}; partial file retained for diagnosis."
                    )
                os.replace(partial, target)

            actual_sha = sha256(target)
            with record_path.open("a", encoding="utf-8") as record:
                record.write(
                    f"{filename}\t{url}\t{target.stat().st_size}\t{actual_sha}\t"
                    f"{datetime.now(timezone.utc).isoformat()}\n"
                )
            completed += 1
        print(f"[complete] {completed} DEM tiles present and checksum-recorded.")
        print(f"[manifest] {record_path}")
        PY
        '''
    ).lstrip()
    script_path.write_text(script, encoding="utf-8")
    script_path.chmod(0o755)
    print(f"[prepared] MSI DEM downloader: {script_path}")
    print("[policy] No download submitted; inspect live MSI limits before sbatch.")
    return {"script": str(script_path), "manifest": str(project.paths["dem_tile_manifest"])}


class _HrefParser(HTMLParser):
    """Collect links from NOAA directory and archive pages."""

    def __init__(self) -> None:
        super().__init__()
        self.hrefs: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag.lower() == "a":
            href = dict(attrs).get("href")
            if href:
                self.hrefs.append(href)


def _fetch_url(url: str) -> bytes:
    request = Request(url, headers={"User-Agent": "coastal-protection-research/1.0"})
    with urlopen(request, timeout=120) as response:
        return response.read()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _save_source(url: str, destination: Path) -> dict[str, object]:
    """Download one source without overwriting an existing snapshot file."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    payload = _fetch_url(url)
    if destination.exists():
        existing_sha = _sha256(destination)
        incoming_sha = hashlib.sha256(payload).hexdigest()
        if existing_sha != incoming_sha:
            raise FileExistsError(
                f"Snapshot file differs from current source; preserved existing file: {destination}"
            )
    else:
        temporary = destination.with_name(destination.name + ".part")
        temporary.write_bytes(payload)
        temporary.replace(destination)
    return {
        "url": url,
        "path": str(destination),
        "bytes": destination.stat().st_size,
        "sha256": _sha256(destination),
    }


def _nhc_hurdat_sources() -> list[dict[str, str]]:
    """Discover latest Atlantic and Northeast Pacific HURDAT2 files from NHC."""
    pages = (
        "https://www.nhc.noaa.gov/data/",
        "https://www.nhc.noaa.gov/data/hurdat/",
    )
    hrefs: set[str] = set()
    errors: list[str] = []
    for page in pages:
        try:
            parser = _HrefParser()
            parser.feed(_fetch_url(page).decode("utf-8", errors="replace"))
            hrefs.update(urljoin(page, href) for href in parser.hrefs)
        except Exception as exc:
            errors.append(f"{page}: {exc}")

    candidates: dict[str, tuple[int, str, str]] = {}
    pattern = re.compile(r"hurdat2.*\.txt$", re.IGNORECASE)
    year_range = re.compile(r"((?:18|19|20)\d{2})[-_]((?:18|19|20)\d{2})")
    for url in hrefs:
        filename = Path(unquote(urlparse(url).path)).name
        if not pattern.fullmatch(filename):
            continue
        match = year_range.search(filename)
        if not match:
            continue
        first_year, last_year = map(int, match.groups())
        lower_name = filename.lower()
        if "nepac" in lower_name or first_year == 1949:
            basin = "northeast_pacific"
        elif first_year == 1851:
            basin = "atlantic"
        else:
            continue
        # NHC filename date suffix gives deterministic preference among releases.
        version_match = re.search(r"-(\d{6})\.txt$", filename)
        version = version_match.group(1) if version_match else "000000"
        candidate = (last_year, version, url)
        if basin not in candidates or candidate[:2] > candidates[basin][:2]:
            candidates[basin] = candidate

    if not candidates:
        raise RuntimeError(
            "Could not discover NHC HURDAT2 files. " + "; ".join(errors)
        )
    missing_basins = {"atlantic", "northeast_pacific"} - set(candidates)
    if missing_basins:
        raise RuntimeError(f"NHC HURDAT2 archive missing basin links: {sorted(missing_basins)}")
    return [
        {"basin": basin, "last_year": str(values[0]), "url": values[2]}
        for basin, values in sorted(candidates.items())
    ]


def _nhc_2026_gis_best_tracks(start_year: int, end_year: int) -> list[str]:
    """Discover official NHC GIS best-track archives for the requested seasons."""
    index_url = "https://ftp.nhc.noaa.gov/atcf/gis/btk/"
    parser = _HrefParser()
    parser.feed(_fetch_url(index_url).decode("utf-8", errors="replace"))
    pattern = re.compile(r"^(?P<basin>al|ep)(?P<number>\d{2})(?P<year>\d{4})_best_track\.zip$", re.I)
    urls: list[str] = []
    for href in parser.hrefs:
        filename = Path(unquote(urlparse(href).path)).name
        match = pattern.fullmatch(filename)
        if match and start_year <= int(match.group("year")) <= end_year:
            urls.append(urljoin(index_url, href))
    return sorted(set(urls))


def download_nhc_storm_tracks(project) -> dict[str, object]:
    """Stage official NHC tracks for 1996-2026 in a dated, checksummed snapshot.

    Final HURDAT2 archives provide historical Atlantic and Northeast Pacific
    records through their published end year. Current-year GIS best-track ZIPs
    supplement HURDAT2 because the season is not yet finalized.
    """
    start_year = int(project.config.get("storm_start_year", 1996))
    end_year = int(project.config.get("storm_end_year", 2026))
    if start_year < 1851 or end_year < start_year:
        raise ValueError(f"Invalid storm-year range: {start_year}-{end_year}")

    retrieval_time = datetime.now(timezone.utc)
    snapshot = (
        project.paths["nhc_storm_track_root"]
        / "snapshots"
        / retrieval_time.strftime("%Y%m%d")
    )
    snapshot.mkdir(parents=True, exist_ok=True)

    hurdat_sources = _nhc_hurdat_sources()
    hurdat_files: list[dict[str, object]] = []
    for source in hurdat_sources:
        basin_dir = snapshot / "hurdat2" / source["basin"]
        filename = Path(unquote(urlparse(source["url"]).path)).name
        item = _save_source(source["url"], basin_dir / filename)
        item.update({"basin": source["basin"], "published_through_year": int(source["last_year"])})
        hurdat_files.append(item)

    gis_urls = _nhc_2026_gis_best_tracks(start_year, end_year)
    gis_files: list[dict[str, object]] = []
    for url in gis_urls:
        filename = Path(unquote(urlparse(url).path)).name
        gis_files.append(_save_source(url, snapshot / "nhc_gis_best_track" / filename))

    current_year_files = [
        item for item in gis_files
        if end_year == int(re.search(r"(\d{4})_best_track\.zip$", str(item["path"])).group(1))
    ]
    final_years = {int(item["published_through_year"]) for item in hurdat_files}
    if not hurdat_files or max(final_years) < min(end_year - 1, 2025):
        raise RuntimeError(
            f"Latest finalized HURDAT2 source ends before expected 2025 coverage: {sorted(final_years)}"
        )
    if end_year >= datetime.now(timezone.utc).year and not current_year_files:
        raise RuntimeError(
            f"No NHC GIS best-track files found for current season {end_year}; snapshot not marked complete."
        )

    manifest = {
        "dataset": "NHC tropical cyclone best tracks",
        "requested_years": {"start": start_year, "end": end_year},
        "retrieved_utc": retrieval_time.isoformat(),
        "status": {
            "final_hurdat2_through_year": max(final_years),
            "current_season_gis_tracks": "preliminary; current through retrieval date",
            "current_season_storm_count": len(current_year_files),
        },
        "scope_note": (
            "HURDAT2 source files contain full basin histories; downstream processing must filter "
            f"records to {start_year}-{end_year}. Current-season best-track GIS files are preliminary "
            "and may be revised after season-end review."
        ),
        "sources": {
            "nhc_hurdat2": "https://www.nhc.noaa.gov/data/",
            "nhc_gis_best_tracks": "https://ftp.nhc.noaa.gov/atcf/gis/btk/",
        },
        "hurdat2_files": hurdat_files,
        "gis_best_track_files": gis_files,
    }
    manifest_path = snapshot / "source_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"[download] Final HURDAT2 files: {len(hurdat_files)}")
    print(f"[download] NHC GIS best-track ZIPs: {len(gis_files)}")
    print(f"[coverage] finalized tracks through {max(final_years)}; current season preliminary")
    print(f"[manifest] {manifest_path}")
    return {
        "snapshot": str(snapshot),
        "manifest": str(manifest_path),
        "hurdat2_files": len(hurdat_files),
        "gis_best_track_files": len(gis_files),
        "current_season_storm_count": len(current_year_files),
    }



def download_coastal_dem_inputs(config=None, project_root=None, dem_root=None):
    """Download NOAA coastal land-mask inputs and USGS 3DEP NAVD88 DEM tiles.

    Downloads are raw, reproducibly catalogued inputs. Study geometry comes from
    NOAA's 452-county shoreline layer, restricted to CONUS and excluding counties
    intersecting NOAA Great Lakes waterbodies. DEM search uses 1-degree cells
    intersecting those county bounds; this may include some non-study pixels.
    """
    import hashlib
    import json
    import math
    import os
    import shutil
    import time
    from datetime import datetime, timezone
    from pathlib import Path
    from urllib.error import HTTPError, URLError
    from urllib.parse import urlencode, urlparse, unquote
    from urllib.request import Request, urlopen

    import numpy as np
    import rasterio
    from shapely.geometry import shape
    from shapely.ops import unary_union

    if project_root is None and config is not None:
        project_root = getattr(config, "project_root", None)
        if project_root is None and isinstance(config, (str, os.PathLike)):
            project_root = config
    project_root = Path(
        project_root
        or os.environ.get("COASTAL_PROTECTION_PROJECT_ROOT")
        or Path(__file__).resolve().parent.parent
    ).expanduser().resolve()
    dem_root = Path(
        dem_root
        or os.environ.get("COASTAL_PROTECTION_DEM_ROOT")
        or project_root / "data/raw/usgs_3dep_13arcsec_dem"
    ).expanduser().resolve()
    dem_dir = dem_root / "tiles"
    land_dir = dem_root / "land_mask"
    dem_dir.mkdir(parents=True, exist_ok=True)
    land_dir.mkdir(parents=True, exist_ok=True)

    user_agent = "coastal-protection-research/1.0 (USGS TNM and NOAA public data)"

    def get_bytes(url, timeout=180):
        req = Request(url, headers={"User-Agent": user_agent})
        last_error = None
        for attempt in range(5):
            try:
                with urlopen(req, timeout=timeout) as response:
                    return response.read()
            except (HTTPError, URLError, TimeoutError) as exc:
                last_error = exc
                time.sleep(min(2 ** attempt, 20))
        raise RuntimeError(f"Request failed after retries: {url}: {last_error}")

    def get_json(url, params):
        return json.loads(get_bytes(url + "?" + urlencode(params)).decode("utf-8"))

    def arcgis_features(layer_url, fields="*"):
        ids_result = get_json(layer_url + "/query", {
            "where": "1=1", "returnIdsOnly": "true", "f": "json"
        })
        ids = ids_result.get("objectIds") or []
        features = []
        for start in range(0, len(ids), 100):
            result = get_json(layer_url + "/query", {
                "objectIds": ",".join(map(str, ids[start:start + 100])),
                "outFields": fields, "returnGeometry": "true", "outSR": "4326",
                "f": "geojson"
            })
            features.extend(result.get("features", []))
        return features

    def sha256(path):
        digest = hashlib.sha256()
        with Path(path).open("rb") as handle:
            for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
                digest.update(block)
        return digest.hexdigest()

    def download(url, destination, expected_size=None):
        destination = Path(destination)
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists() and (expected_size is None or destination.stat().st_size == expected_size):
            return {"path": str(destination), "bytes": destination.stat().st_size,
                    "sha256": sha256(destination), "status": "already_present"}
        partial = destination.with_suffix(destination.suffix + ".part")
        offset = partial.stat().st_size if partial.exists() else 0
        headers = {"User-Agent": user_agent}
        if offset:
            headers["Range"] = f"bytes={offset}-"
        req = Request(url, headers=headers)
        try:
            with urlopen(req, timeout=300) as response:
                append = offset > 0 and getattr(response, "status", 200) == 206
                if not append:
                    offset = 0
                mode = "ab" if append else "wb"
                with partial.open(mode) as out:
                    while True:
                        block = response.read(8 * 1024 * 1024)
                        if not block:
                            break
                        out.write(block)
        except Exception:
            raise
        actual = partial.stat().st_size
        if expected_size is not None and actual != expected_size:
            raise RuntimeError(f"Download size mismatch for {url}: expected {expected_size}, got {actual}; partial kept at {partial}")
        partial.replace(destination)
        return {"path": str(destination), "bytes": actual,
                "sha256": sha256(destination), "status": "downloaded"}

    county_layer = "https://www.coast.noaa.gov/arcgis/rest/services/Landcover/Coastal_County_Update_Review/MapServer/9"
    great_lakes_layer = "https://www.coast.noaa.gov/arcgis/rest/services/Landcover/Coastal_County_Update_Review/MapServer/5"
    county_features = arcgis_features(county_layer, "fips,st_abbr,cntyname")
    lake_features = arcgis_features(great_lakes_layer, "*")
    lake_geometries = [shape(f["geometry"]) for f in lake_features if f.get("geometry")]
    great_lakes = unary_union(lake_geometries) if lake_geometries else None
    non_conus = {"AK", "HI", "PR", "VI", "GU", "AS", "MP", "UM"}
    kept = []
    excluded_great_lakes_fips = []
    county_geometries = []
    for feature in county_features:
        props = feature.get("properties", {})
        state = str(props.get("st_abbr", "")).upper()
        fips = str(props.get("fips", "")).zfill(5)
        if state in non_conus or not feature.get("geometry"):
            continue
        geom = shape(feature["geometry"])
        if great_lakes is not None and geom.intersects(great_lakes):
            excluded_great_lakes_fips.append(fips)
            continue
        kept.append(feature)
        county_geometries.append(geom)
    if not kept:
        raise RuntimeError("NOAA query returned no CONUS shoreline counties after Great Lakes exclusion")

    boundary_path = dem_root / "noaa_shoreline_counties_conus_excluding_great_lakes.geojson"
    boundary_payload = {
        "type": "FeatureCollection", "name": "NOAA CONUS shoreline counties excluding Great Lakes",
        "crs": {"type": "name", "properties": {"name": "urn:ogc:def:crs:OGC:1.3:CRS84"}},
        "features": kept
    }
    boundary_path.write_text(json.dumps(boundary_payload), encoding="utf-8")

    # DEM 1/3 arc-second coverage is queried by one-degree cells intersecting
    # county bounding boxes; exact pixel clipping is a later processing step.
    cells = set()
    for geom in county_geometries:
        minx, miny, maxx, maxy = geom.bounds
        minx, maxx = max(minx, -126.0), min(maxx, -65.0)
        miny, maxy = max(miny, 23.0), min(maxy, 51.0)
        if minx >= maxx or miny >= maxy:
            continue
        for lon in range(math.floor(minx), math.floor(maxx) + 1):
            for lat in range(math.floor(miny), math.floor(maxy) + 1):
                cells.add((lon, lat))

    tnm_url = "https://tnmaccess.nationalmap.gov/api/v1/products"
    dataset = "Digital Elevation Model (DEM) 1/3 arc-second"
    products_by_url = {}
    for index, (lon, lat) in enumerate(sorted(cells), start=1):
        params = {
            "datasets": dataset,
            "bbox": f"{lon},{lat},{lon + 1},{lat + 1}",
            "prodFormats": "GeoTIFF",
            "max": 1000,
            "outputFormat": "JSON"
        }
        try:
            result = get_json(tnm_url, params)
        except Exception as exc:
            raise RuntimeError(f"USGS TNM query failed for 1-degree cell {lon},{lat}: {exc}") from exc
        for item in result.get("items", []):
            url = item.get("downloadURL")
            if url:
                products_by_url[url] = item
        print(f"[dem-catalog] cell {index}/{len(cells)} ({lon},{lat}); unique tiles={len(products_by_url)}", flush=True)
        time.sleep(0.15)
    if not products_by_url:
        raise RuntimeError("USGS TNM returned no 1/3 arc-second GeoTIFF products; check dataset name/API response")

    products = sorted(products_by_url.values(), key=lambda x: x.get("downloadURL", ""))
    total_known = sum(int(p.get("sizeInBytes") or 0) for p in products)
    ccap_url = "https://ocmgeodatastor1.blob.core.windows.net/ccap/bulk_download/C-CAP_Regional_30-meter_Data/C-CAP_Regional_Land_Cover_Classification/CONUS/conus_2021_ccap_landcover.tif"
    ccap_xml_url = ccap_url[:-4] + ".xml"
    ccap_path = land_dir / "conus_2021_ccap_landcover.tif"
    xml_path = land_dir / "conus_2021_ccap_landcover.xml"
    mask_path = land_dir / "conus_2021_ccap_land_mask.tif"

    disk = shutil.disk_usage(dem_root)
    required = total_known + (ccap_path.stat().st_size if ccap_path.exists() else 700_000_000) + 500_000_000
    if disk.free < required:
        raise RuntimeError(f"Insufficient free space at {dem_root}: need about {required:,} bytes, have {disk.free:,}; set COASTAL_PROTECTION_DEM_ROOT to MSI scratch")

    tile_records = []
    for index, item in enumerate(products, start=1):
        url = item["downloadURL"]
        name = unquote(Path(urlparse(url).path).name) or f"3dep_13arcsec_{index:05d}.tif"
        if not name.lower().endswith((".tif", ".tiff", ".zip")):
            name += ".tif"
        path = dem_dir / name
        record = download(url, path, int(item["sizeInBytes"]) if item.get("sizeInBytes") else None)
        record.update({
            "title": item.get("title"), "sourceOriginId": item.get("sourceOriginId"),
            "publicationDate": item.get("publicationDate"),
            "lastUpdated": item.get("lastUpdated"), "downloadURL": url,
            "vertical_datum": "NAVD88", "elevation_units": "meters",
            "horizontal_datum": "NAD83"
        })
        tile_records.append(record)
        print(f"[dem-download] tile {index}/{len(products)}: {name} ({record['status']})", flush=True)

    ccap_record = download(ccap_url, ccap_path)
    xml_record = download(ccap_xml_url, xml_path)
    with rasterio.open(ccap_path) as source:
        profile = source.profile.copy()
        profile.update(driver="GTiff", count=1, dtype="uint8", nodata=255,
                       compress="deflate", predictor=2, tiled=True)
        with rasterio.open(mask_path, "w", **profile) as target:
            for _, window in source.block_windows(1):
                values = source.read(1, window=window)
                valid = (source.read_masks(1, window=window) > 0) & (values != 0)
                mask = np.full(values.shape, 255, dtype=np.uint8)
                mask[valid & (values == 21)] = 0
                mask[valid & (values != 21)] = 1
                target.write(mask, 1, window=window)
    mask_record = {"path": str(mask_path), "bytes": mask_path.stat().st_size,
                   "sha256": sha256(mask_path), "status": "written",
                   "rule": "valid C-CAP cells: 1=land, 0=class 21 Open Water, 255=NoData; wetland classes remain land"}

    storm_manifests = sorted((project_root / "data/raw/nhc_storm_tracks").glob("snapshots/*/source_manifest.json"))
    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "study_boundary": {
            "path": str(boundary_path), "source": county_layer,
            "source_description": "NOAA Coastal County Update Review, Original Shoreline Counties (2010 boundaries), 452-county definition layer",
            "county_count": len(kept), "excluded_great_lakes_counties": sorted(set(excluded_great_lakes_fips)),
            "great_lakes_source": great_lakes_layer, "crs": "EPSG:4326"
        },
        "storm_track_manifest": str(storm_manifests[-1]) if storm_manifests else None,
        "dem": {
            "dataset": dataset, "search_api": tnm_url, "candidate_1degree_cells": len(cells),
            "tile_count": len(tile_records), "tiles": tile_records,
            "horizontal_datum": "NAD83", "vertical_datum": "NAVD88",
            "elevation_units": "meters", "resolution": "1/3 arc-second (approximately 10 m)",
            "note": "Raw tiles selected by 1-degree cells intersecting shoreline-county bounding boxes; trim to exact study geometry before analysis."
        },
        "land_mask": {
            "raster": ccap_record, "metadata": xml_record, "binary_mask": mask_record,
            "source": ccap_url, "vintage": 2021, "native_resolution": "30 m",
            "classification": "C-CAP class 21 is Open Water; valid non-water pixels, including wetland classes 13-18, are coded land.",
            "alignment": "Keep native C-CAP grid; resample mask to DEM grids with nearest-neighbor only when needed."
        }
    }
    manifest_path = dem_root / "coastal_dem_landmask_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    total_downloaded = sum(r["bytes"] for r in tile_records)
    print(f"[done] DEM tiles: {len(tile_records)} ({total_downloaded:,} bytes); land mask: {mask_path}; manifest: {manifest_path}", flush=True)
    return manifest



def download_all_ccap_vintages(config=None, project_root=None, output_root=None):
    """Download every available NOAA CONUS C-CAP regional land-cover vintage.

    Fetches each listed GeoTIFF and available metadata companions. When rasterio
    is installed, also writes per-vintage binary masks: 1=non-open-water land,
    0=C-CAP class 21 Open Water, 255=NoData. Native grids remain unwarped.
    """
    import hashlib
    import json
    import os
    import re
    import shutil
    import time
    from datetime import datetime, timezone
    from html.parser import HTMLParser
    from pathlib import Path
    from urllib.error import HTTPError, URLError
    from urllib.parse import urljoin
    from urllib.request import Request, urlopen

    class Links(HTMLParser):
        def __init__(self):
            super().__init__()
            self.hrefs = set()
        def handle_starttag(self, tag, attrs):
            if tag.lower() == "a":
                href = dict(attrs).get("href")
                if href:
                    self.hrefs.add(href)

    if project_root is None and config is not None:
        project_root = getattr(config, "project_root", None)
        if project_root is None and isinstance(config, (str, os.PathLike)):
            project_root = config
    project_root = Path(
        project_root or os.environ.get("COASTAL_PROTECTION_PROJECT_ROOT")
        or Path(__file__).resolve().parent.parent
    ).expanduser().resolve()
    output_root = Path(
        output_root or os.environ.get("COASTAL_PROTECTION_CCAP_ROOT")
        or project_root / "data/raw/ccap_30m_all_vintages"
    ).expanduser().resolve()
    raster_dir = output_root / "rasters"
    metadata_dir = output_root / "metadata"
    auxiliary_dir = output_root / "auxiliary"
    mask_dir = output_root / "land_masks"
    for folder in (raster_dir, metadata_dir, auxiliary_dir, mask_dir):
        folder.mkdir(parents=True, exist_ok=True)

    user_agent = "coastal-protection-research/1.0 NOAA C-CAP archive download"
    base_url = "https://ocmgeodatastor1.blob.core.windows.net/ccap/bulk_download/C-CAP_Regional_30-meter_Data/C-CAP_Regional_Land_Cover_Classification/CONUS/"
    listing_url = urljoin(base_url, "index.html")

    def open_url(url, method="GET", headers=None, timeout=180):
        request_headers = {"User-Agent": user_agent}
        if headers:
            request_headers.update(headers)
        request = Request(url, headers=request_headers, method=method)
        return urlopen(request, timeout=timeout)

    def head_size(url):
        try:
            with open_url(url, method="HEAD") as response:
                value = response.headers.get("Content-Length")
                return int(value) if value else None
        except Exception:
            return None

    def file_hash(path):
        digest = hashlib.sha256()
        with Path(path).open("rb") as handle:
            for chunk in iter(lambda: handle.read(8 * 1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()

    def fetch(url, destination, expected_size=None):
        destination = Path(destination)
        partial = destination.with_suffix(destination.suffix + ".part")
        if destination.exists() and (expected_size is None or destination.stat().st_size == expected_size):
            return {"path": str(destination), "bytes": destination.stat().st_size,
                    "sha256": file_hash(destination), "status": "already_present"}
        offset = partial.stat().st_size if partial.exists() else 0
        headers = {"Range": f"bytes={offset}-"} if offset else {}
        try:
            with open_url(url, headers=headers, timeout=300) as response:
                append = offset > 0 and getattr(response, "status", 200) == 206
                if not append:
                    offset = 0
                digest = hashlib.sha256()
                if append:
                    with partial.open("rb") as old:
                        for chunk in iter(lambda: old.read(8 * 1024 * 1024), b""):
                            digest.update(chunk)
                mode = "ab" if append else "wb"
                with partial.open(mode) as out:
                    while True:
                        chunk = response.read(8 * 1024 * 1024)
                        if not chunk:
                            break
                        out.write(chunk)
                        digest.update(chunk)
        except (HTTPError, URLError, TimeoutError) as exc:
            raise RuntimeError(f"C-CAP download failed: {url}: {exc}") from exc
        actual = partial.stat().st_size
        if expected_size is not None and actual != expected_size:
            raise RuntimeError(f"C-CAP size mismatch: {url}; expected {expected_size}, got {actual}; partial retained")
        partial.replace(destination)
        return {"path": str(destination), "bytes": actual,
                "sha256": digest.hexdigest(), "status": "downloaded"}

    with open_url(listing_url) as response:
        html = response.read().decode("utf-8", errors="replace")
    parser = Links()
    parser.feed(html)
    tif_names = sorted({
        Path(href).name for href in parser.hrefs
        if re.fullmatch(r"conus_\d{4}_ccap_landcover\.tif", Path(href).name, re.I)
    })
    if not tif_names:
        raise RuntimeError(f"NOAA CONUS C-CAP listing had no matching land-cover GeoTIFFs: {listing_url}")
    years = [int(re.search(r"(\d{4})", name).group(1)) for name in tif_names]
    print(f"[ccap] NOAA listing: {len(tif_names)} vintages {years[0]}-{years[-1]}: {years}", flush=True)

    inventory = []
    for tif_name, year in zip(tif_names, years):
        tif_url = urljoin(base_url, tif_name)
        xml_name = tif_name[:-4] + ".xml"
        aux_name = tif_name + ".aux.xml"
        links_by_name = {Path(href).name for href in parser.hrefs}
        companions = []
        if xml_name in links_by_name:
            companions.append(("metadata", xml_name, urljoin(base_url, xml_name), metadata_dir / xml_name))
        if aux_name in links_by_name:
            companions.append(("auxiliary", aux_name, urljoin(base_url, aux_name), auxiliary_dir / aux_name))
        files = [("raster", tif_name, tif_url, raster_dir / tif_name)] + companions
        file_entries = []
        for kind, name, url, destination in files:
            file_entries.append({
                "kind": kind, "name": name, "url": url,
                "destination": str(destination), "expected_bytes": head_size(url)
            })
        inventory.append({"year": year, "files": file_entries})

    try:
        import numpy as np
        import rasterio
        can_make_masks = True
    except ImportError:
        np = rasterio = None
        can_make_masks = False
        print("[ccap] rasterio/numpy unavailable; rasters will download, binary masks skipped", flush=True)

    missing_bytes = sum(
        entry["expected_bytes"] or 0
        for vintage in inventory for entry in vintage["files"]
        if not Path(entry["destination"]).exists()
    )
    mask_reserve = sum(
        entry["expected_bytes"] or 0
        for vintage in inventory for entry in vintage["files"]
        if entry["kind"] == "raster"
    ) if can_make_masks else 0
    disk = shutil.disk_usage(output_root)
    needed = missing_bytes + mask_reserve + 512_000_000
    if disk.free < needed:
        raise RuntimeError(f"Insufficient free space at {output_root}: estimated need {needed:,} bytes, free {disk.free:,}")

    vintage_results = []
    for vintage in inventory:
        result = {"year": vintage["year"], "files": []}
        tif_path = None
        for entry in vintage["files"]:
            saved = fetch(entry["url"], entry["destination"], entry["expected_bytes"])
            record = {**entry, **saved}
            result["files"].append(record)
            if entry["kind"] == "raster":
                tif_path = Path(entry["destination"])
            print(f"[ccap] {vintage['year']} {entry['kind']}: {saved['status']} ({saved['bytes']:,} bytes)", flush=True)
        result["mask"] = None
        if can_make_masks and tif_path is not None:
            mask_path = mask_dir / f"conus_{vintage['year']}_ccap_land_mask.tif"
            if not mask_path.exists() or mask_path.stat().st_mtime < tif_path.stat().st_mtime:
                with rasterio.open(tif_path) as source:
                    profile = source.profile.copy()
                    profile.update(driver="GTiff", count=1, dtype="uint8", nodata=255,
                                   compress="deflate", predictor=2, tiled=True)
                    with rasterio.open(mask_path, "w", **profile) as target:
                        for _, window in source.block_windows(1):
                            values = source.read(1, window=window)
                            valid = (source.read_masks(1, window=window) > 0) & (values != 0)
                            mask = np.full(values.shape, 255, dtype=np.uint8)
                            mask[valid & (values == 21)] = 0
                            mask[valid & (values != 21)] = 1
                            target.write(mask, 1, window=window)
            with rasterio.open(tif_path) as source:
                native_resolution = [abs(float(v)) for v in source.res]
                crs = str(source.crs)
            result["mask"] = {
                "path": str(mask_path), "bytes": mask_path.stat().st_size,
                "sha256": file_hash(mask_path), "rule": "1=valid non-Open-Water class; 0=C-CAP class 21 Open Water; 255=NoData",
                "native_resolution": native_resolution, "crs": crs
            }
        vintage_results.append(result)
        time.sleep(0.1)

    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "source_page": "https://coast.noaa.gov/digitalcoast/data/ccapregional.html",
        "source_directory": listing_url,
        "product": "NOAA C-CAP Regional Land Cover Classification, CONUS",
        "years_found_in_official_listing": years,
        "vintage_count": len(years),
        "notes": [
            "Downloaded every CONUS land-cover GeoTIFF linked in NOAA directory at run time, plus listed XML and .tif.aux.xml companions.",
            "No reprojection or resampling; each native raster grid and mapping footprint preserved.",
            "Class 21 Open Water coded 0 in binary land mask; other valid classes, including wetlands 13-18, coded 1; NoData coded 255.",
            "Native resolution recorded per vintage from raster metadata; do not assume all vintages share identical grid or resolution."
        ],
        "vintages": vintage_results
    }
    manifest_path = output_root / "ccap_all_conus_vintages_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"[ccap-done] {len(years)} vintages; manifest: {manifest_path}", flush=True)
    return manifest
